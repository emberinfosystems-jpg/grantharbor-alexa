/**
 * Pro licensing — offline, signature-verified.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🛑 WHY A SIGNED KEY AND NOT A LICENCE SERVER
 *
 * The usual model is: app calls home, server says yes. That would break the one promise
 * this product actually makes. GrantHarbor declares `localFirst: true` and its published
 * data-flow map lists exactly ONE outbound connection (Grants.gov, carrying nothing about
 * the user). A licence check would add a second — one that reports, on every launch, that
 * this specific customer is using the app right now. It would also mean the paid features
 * stop working on a plane, or when EIS's server is down, or in five years when it is gone.
 *
 * So the licence is an Ed25519-signed token. The app carries only the PUBLIC key and verifies
 * OFFLINE. A customer who paid keeps working with no dependency on us continuing to exist —
 * [[feedback_independence_is_the_goal]] applied to our own customers rather than to ourselves.
 *
 * 🛑 AMENDED 2026-08-25 — the SUBSCRIPTION tier does contact us, and this file used to claim
 * it "never phones home". That stopped being true the moment auto-renewal was designed, and a
 * header that contradicts the code below it is exactly the kind of confident falsehood the
 * rest of this codebase spends its time catching. The honest statement:
 *
 *   • The PERPETUAL licence ($39) never contacts anything. Ever.
 *   • The SUBSCRIPTION ($19/mo) fetches a renewal key roughly once a cycle — and the
 *     customer can switch that off, which also stops the subscription renewing.
 *   • VERIFICATION is always offline. The fetch retrieves a new signed token; it never asks
 *     permission to run, so a dead server or a plane cannot disable a paid feature.
 *
 * 🛑 The private key lives in the VDR (`09_KEYS_GRANTHARBOR`), NEVER in this repo or bundle.
 * Anyone holding it can mint unlimited Pro licences. The public key below is safe to ship —
 * it can verify signatures and cannot create them.
 *
 * HONEST LIMIT: a determined user can patch a local binary, and no client-side check
 * survives that. This stops casual copying and keeps honest customers honest, which is all
 * offline licensing can ever do. Pretending otherwise would just buy obfuscation nobody
 * benefits from.
 * ─────────────────────────────────────────────────────────────────────────────
 */
import { app, safeStorage } from 'electron';
import { createPublicKey, verify as edVerify, createHash } from 'crypto';
import { existsSync, readFileSync, writeFileSync, unlinkSync } from 'fs';
import { join } from 'path';
/** Raw 32-byte Ed25519 public key, base64. Generated by tools/keygen.mjs 2026-08-25. */
const LICENSE_PUBLIC_KEY = 'chUcvlF7wT3zOMoK0ICW7Dpb11JGOBECEUVAgBk6iRE=';
/** UTC day number, so comparisons never shift across a timezone boundary. */
function utcDay(d) {
    return Math.floor(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()) / 86400000);
}
function parseDay(iso) {
    const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || '').trim());
    if (!m)
        return null;
    const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
    // Reject impossible dates like 2026-02-30, which Date silently rolls forward.
    if (d.getUTCMonth() !== +m[2] - 1 || d.getUTCDate() !== +m[3])
        return null;
    return utcDay(d);
}
/**
 * 🛑 HIGH-WATER MARK against clock rollback. Everything about an offline expiry check
 * trusts the local clock, and setting a clock back is the obvious way to extend a lapsed
 * subscription forever. We remember the latest date this install has ever seen and treat
 * "today" as no earlier than that, so winding the clock back buys nothing.
 *
 * It deliberately does NOT hard-fail on a backwards clock: people legitimately fix a wrong
 * clock, cross timezones, and restore machines. Refusing to run would turn an honest
 * correction into a support ticket.
 */
function effectiveToday() {
    const markPath = join(app.getPath('userData'), '.timemark');
    const now = utcDay(new Date());
    let seen = 0;
    try {
        if (existsSync(markPath))
            seen = parseInt(readFileSync(markPath, 'utf8').trim(), 10) || 0;
    }
    catch { /* unreadable — treat as unseen */ }
    const today = Math.max(now, seen);
    if (today > seen) {
        try {
            writeFileSync(markPath, String(today));
        }
        catch { /* best effort */ }
    }
    return today;
}
/**
 * Days Pro keeps working past the ACCESS-through date.
 *
 * 🛑 RECONCILED 2026-08-25. This was 14 days, chosen when `x` was the BILLING date and the
 * grace period was the only cushion in the system. Once access started being issued at
 * `billing + 15`, keeping a 14-day grace on top meant **29 days of Pro after the money
 * stopped** — a cancelling customer would get most of a free month, every time.
 *
 * The 15-day access buffer now does the real work: failed cards, offline stretches and
 * renewal-fetch retries all fit inside it, before this constant is ever consulted. What is
 * left for grace is one narrow job — 🛑 THE CLOCK LIES. This machine's own clock has drifted
 * 11 days ([[infra_machine_clock_never_syncs]]), and an offline expiry check trusts the local
 * clock completely. Three days absorbs ordinary drift and timezone edges without handing
 * anybody a free month.
 *
 * 🛑 Two cushions with overlapping jobs is how a system quietly gives away a month. If the
 * access buffer changes, revisit this number in the same commit.
 */
const GRACE_DAYS = 3;
/**
 * Days of ACCESS granted beyond each billing boundary. The issuer adds this; the app only
 * reads the resulting date. Kept here so both halves of the system name the same number.
 */
export const ACCESS_BUFFER_DAYS = 15;
/**
 * 🛑 AUTO-RENEWAL IS A SWITCH THE CUSTOMER OWNS.
 *
 * Fetching a renewal key means contacting us on a schedule — the one thing this app
 * otherwise never does. That is only defensible if it is a choice rather than something
 * done TO them, so it is a visible toggle in Settings, and turning it off does two things
 * at once: it stops the network call, and it stops the subscription renewing.
 *
 * Those two belong together. An app that keeps phoning home after you asked it not to is
 * spyware; a subscription you can only escape by hunting through a website is a dark
 * pattern. One switch, both meanings, stated plainly.
 *
 * 🛑 Turning it off never revokes access already paid for — the current access window runs
 * to its end and then drops to Basic. Cancelling must not feel like a punishment.
 */
function autoRenewPath() {
    return join(app.getPath('userData'), '.autorenew');
}
export function autoRenewEnabled() {
    // Default ON: a subscription that silently stops renewing would cut a paying customer
    // off for a setting they never touched.
    try {
        if (!existsSync(autoRenewPath()))
            return true;
        return readFileSync(autoRenewPath(), 'utf8').trim() !== 'off';
    }
    catch {
        return true;
    }
}
export function setAutoRenew(on) {
    writeFileSync(autoRenewPath(), on ? 'on' : 'off');
    return on;
}
function keyObject() {
    // Wrap the raw key in the DER SPKI prefix Ed25519 uses, so we can ship 32 bytes
    // instead of a PEM blob.
    const der = Buffer.concat([
        Buffer.from('302a300506032b6570032100', 'hex'),
        Buffer.from(LICENSE_PUBLIC_KEY, 'base64')
    ]);
    return createPublicKey({ key: der, format: 'der', type: 'spki' });
}
function licensePath() {
    return join(app.getPath('userData'), '.license');
}
/**
 * 🛑 BASE32, NOT BASE64URL. Licence keys get printed, emailed, and retyped by hand, so they
 * are grouped with dashes for legibility — and base64url's alphabet CONTAINS `-`. Stripping
 * the grouping dashes therefore also stripped real payload characters, and every genuine key
 * failed verification while forgeries still correctly failed. A licence system that rejects
 * only real customers is the worst possible arrangement, and it looked fine until a genuine
 * key was actually tested.
 *
 * Base32 (RFC 4648, A–Z 2–7) shares no characters with the separator, so grouping is lossless.
 */
const B32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
export function b32encode(buf) {
    let bits = 0;
    let value = 0;
    let out = '';
    for (const byte of buf) {
        value = (value << 8) | byte;
        bits += 8;
        while (bits >= 5) {
            out += B32[(value >>> (bits - 5)) & 31];
            bits -= 5;
        }
    }
    if (bits > 0)
        out += B32[(value << (5 - bits)) & 31];
    return out;
}
function b32decode(str) {
    let bits = 0;
    let value = 0;
    const out = [];
    for (const ch of str) {
        const idx = B32.indexOf(ch);
        if (idx === -1)
            throw new Error('bad character');
        value = (value << 5) | idx;
        bits += 5;
        if (bits >= 8) {
            out.push((value >>> (bits - 8)) & 255);
            bits -= 8;
        }
    }
    return Buffer.from(out);
}
/** Strip formatting so a key can be pasted with or without dashes, in any case. */
function clean(key) {
    return String(key || '').replace(/[\s-]/g, '').toUpperCase();
}
/**
 * Verify a licence key. Returns the payload, or throws with a reason the user can act on.
 *
 * 🛑 The email binding is checked by the CALLER against the signed-in account. Verifying the
 * signature alone would make any leaked key work for everyone — the signature proves the key
 * is genuine, not that it belongs to this person.
 */
export function verifyKey(key) {
    const raw = clean(key);
    if (!raw)
        throw new Error('Enter your licence key.');
    let decoded;
    try {
        decoded = b32decode(raw);
    }
    catch {
        throw new Error('That does not look like a licence key.');
    }
    // [64-byte signature][json payload]
    if (decoded.length < 80)
        throw new Error('That licence key is incomplete.');
    const sig = decoded.subarray(0, 64);
    const body = decoded.subarray(64);
    if (!edVerify(null, body, keyObject(), sig)) {
        throw new Error('That licence key is not valid.');
    }
    let payload;
    try {
        payload = JSON.parse(body.toString('utf8'));
    }
    catch {
        throw new Error('That licence key is not valid.');
    }
    if (payload.p !== 'pro')
        throw new Error('That licence key is not a Pro licence.');
    if (!payload.e)
        throw new Error('That licence key is not bound to an account.');
    return payload;
}
/**
 * Activate a licence for the signed-in account.
 *
 * The stored blob is encrypted with safeStorage (DPAPI on Windows), which binds it to this
 * OS user — copying `.license` to another machine yields nothing. That is a convenience
 * property, not the security boundary: the signature is what actually matters.
 */
export function activate(key, accountEmail) {
    const payload = verifyKey(key);
    const bound = String(payload.e).toLowerCase().trim();
    const actual = String(accountEmail || '').toLowerCase().trim();
    // 🛑 Compare against a hash too, so a licence can be issued without EIS storing the
    // customer's plaintext email in the key itself if we'd rather not.
    const hashed = createHash('sha256').update(actual).digest('hex').slice(0, 32);
    if (bound !== actual && bound !== hashed) {
        throw new Error(`That licence is registered to a different account (${payload.e}).`);
    }
    if (!safeStorage.isEncryptionAvailable()) {
        throw new Error('OS encryption unavailable — cannot store the licence securely.');
    }
    writeFileSync(licensePath(), safeStorage.encryptString(clean(key)));
    return { plan: 'pro', licensedTo: payload.e, issued: payload.i, order: payload.o };
}
/** Current entitlement. Any doubt resolves to `basic` — never grant Pro on an error path. */
export function status(accountEmail) {
    const p = licensePath();
    if (!existsSync(p) || !safeStorage.isEncryptionAvailable())
        return { plan: 'basic' };
    try {
        const key = safeStorage.decryptString(readFileSync(p));
        const payload = verifyKey(key);
        const bound = String(payload.e).toLowerCase().trim();
        const actual = String(accountEmail || '').toLowerCase().trim();
        const hashed = createHash('sha256').update(actual).digest('hex').slice(0, 32);
        // 🛑 Re-check the binding on EVERY read, not just at activation. Otherwise the first
        // account to activate on a machine silently upgrades every account created afterwards.
        if (bound !== actual && bound !== hashed)
            return { plan: 'basic' };
        const base = {
            plan: 'pro',
            licensedTo: payload.e,
            issued: payload.i,
            order: payload.o,
            autoRenew: autoRenewEnabled()
        };
        // No paid-through date = the perpetual one-time licence. Nothing to expire.
        // A perpetual licence has neither date; a subscription has both.
        if (!payload.x)
            return base;
        const until = parseDay(payload.x);
        // 🛑 An unparseable date means we cannot tell whether this is still paid. Fail CLOSED:
        // an entitlement check that grants Pro on a malformed field is one a forged-looking
        // key could exploit, and the customer-facing cost is a support email, not a data loss.
        if (until === null)
            return { plan: 'basic', lapsed: true };
        const today = effectiveToday();
        const graceDaysLeft = until + GRACE_DAYS - today;
        if (today <= until)
            return { ...base, accessThrough: payload.x, renewsOn: payload.b, graceDaysLeft };
        if (graceDaysLeft >= 0)
            return { ...base, accessThrough: payload.x, renewsOn: payload.b, inGrace: true, graceDaysLeft };
        // Fully lapsed. `lapsed` is carried so the UI can say "your subscription ended"
        // rather than pretending the customer never bought anything.
        return { plan: 'basic', licensedTo: payload.e, accessThrough: payload.x, renewsOn: payload.b, lapsed: true, graceDaysLeft };
    }
    catch {
        return { plan: 'basic' };
    }
}
export function deactivate() {
    const p = licensePath();
    if (existsSync(p))
        unlinkSync(p);
}
